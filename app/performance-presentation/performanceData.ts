// Helper to correlate DB projects with team member
export function matchProjectsToMember(member: TeamMemberPerformance, allProjects: Project[]): Project[] {
  const shortName = member.shortName;
  const fullName = member.fullName;
  
  return allProjects.filter(p => {
    if (!p.supervisor) return false;
    const s = p.supervisor.trim();
    return s.includes(shortName) || fullName.includes(s) || s === shortName;
  });
}

